/**
 * 课堂演示脚本（教师备课口径）。
 *
 * 每个实验一份按步推进的演示流程：讲什么、做什么、问学生什么、
 * 预期听到什么。steps 里的 target 是学生实验页中真实存在的元素
 * 选择器，演示面板的“定位”按钮把对应区块滚动到屏幕中央。
 *
 * 这是教师授课脚本，不是学生答案：现象与提问口径来自实验指导
 * 与备课材料，实物相关处已按“仿真≠实物”口径标注。
 */

export interface PresenterStep {
  /** 步骤名，投屏时的大标题。 */
  title: string;
  /** 教师讲解词，可直接照念或自由发挥。 */
  say: string;
  /** 现场要做的操作；纯讲解步骤可不填。 */
  action?: string;
  /** 抛给学生的问题。 */
  ask?: string;
  /** 预期学生答出或应观察到的结果。 */
  expect?: string;
  /** 定位按钮滚动到的页面元素选择器。 */
  target?: string;
}

export interface LabPresenterScript {
  labId: number;
  steps: PresenterStep[];
}

