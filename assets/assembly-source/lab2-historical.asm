 ;实验2-1
	ORG 0000H
	LJMP MAIN
	ORG 0032H
MAIN:
    MOV R0,#02H
	MOV R1,#08H
	MOV A,#0FEH  //1111 1110
;由上到下
LOOP:
	MOV P1,A   //0111 1111
	LCALL DELAY
	MOV P1,#0FFH
	LCALL DELAY
	RL A		 //1111 1110
	DJNZ R1,LOOP
	MOV R1,#08H
;由下到上
LOOP1:
	RR A		//0111 1111
	MOV P1,A
	LCALL DELAY
	MOV P1,#0FFH
	LCALL DELAY
	DJNZ R1,LOOP1
	MOV R1,#08H
	DJNZ R0,LOOP
;熄灭，后闪烁5次
	MOV P1,#0FFH
	LCALL DELAY
	LCALL DELAY
	LCALL DELAY
	MOV R0,#05H
LOOP2:
	MOV P1,#00H
	LCALL DELAY
	MOV P1,#0FFH
	LCALL DELAY
	DJNZ R0,LOOP2
	SJMP MAIN
;延时程序
DELAY:
	MOV R5,#03H
DELAY1:
	MOV R6,#0FFH
DELAY2:
	MOV R7,#0FFH
DELAY3:
	DJNZ R7,DELAY3
	DJNZ R6,DELAY2
	DJNZ R5,DELAY1
	RET
	END
