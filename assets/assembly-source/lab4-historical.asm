ORG 0000H
LJMP MAIN

ORG 0013H
LJMP INT01

ORG 0040H

MAIN:
	SETB IT1
    SETB EX1
    SETB EA
    SETB PX1
    SJMP $



INT01:
    LCALL DELAY
	JB P3.3,TT
	CPL P1.0
TT:RETI


DELAY:
	MOV R6,#0FFH
DELAY1:
	MOV R7,#0FFH
DELAY2:
	DJNZ R7,DELAY2
	DJNZ R6,DELAY1
	RET

END
